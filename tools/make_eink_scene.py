"""Builds src/EinkScene.h for the E-Ink "Animation" idle mode.

    python tools/make_eink_scene.py <picture.png>

Output:
  EINK_SCENE[5000]  200x200 1-bit base picture (1 = white, MSB = left pixel)
  EINK_BLUE[4096]   64x64 blue-noise thresholds (0..255), used to flip pixels
                    one by one for light effects without the picture crawling

Needs numpy + Pillow.
"""
import sys, os
import numpy as np
from PIL import Image, ImageFilter, ImageOps

CROP = (120, 0, 1370, 1086)   # area of the 1448x1086 reference picture


def bilateral(a, r=3, ss=2.5, sr=0.12, it=2):
    for _ in range(it):
        num = np.zeros_like(a); den = np.zeros_like(a); p = np.pad(a, r, mode='edge')
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                q = p[r + dy:r + dy + a.shape[0], r + dx:r + dx + a.shape[1]]
                w = np.exp(-(dx * dx + dy * dy) / (2 * ss * ss)) * np.exp(-((q - a) ** 2) / (2 * sr * sr))
                num += w * q; den += w
        a = num / den
    return a


def atkinson(g):
    g = g.astype(float).copy(); h, w = g.shape; o = np.zeros((h, w), np.uint8)
    for y in range(h):
        for x in range(w):
            v = g[y, x]; n = 255 if v >= 128 else 0; o[y, x] = 1 if n else 0; e = (v - n) / 8
            for dx, dy in ((1, 0), (2, 0), (-1, 1), (0, 1), (1, 1), (0, 2)):
                if 0 <= x + dx < w and y + dy < h:
                    g[y + dy, x + dx] += e
    return o


def scene(path):
    im = Image.open(path).convert('L').crop(CROP).resize((400, 400), Image.LANCZOS)
    a = np.array(ImageOps.autocontrast(im, cutoff=0.5)).astype(float) / 255
    a = bilateral(a)                                   # flatten textures, keep edges
    a = np.array(Image.fromarray((a * 255).astype(np.uint8)).resize((200, 200), Image.LANCZOS)) / 255
    a = 1 / (1 + np.exp(-6 * (a ** 0.85 - 0.5)))       # S-curve: more solid black/white
    a = (a - a.min()) / (a.max() - a.min()) * 255
    a = np.array(Image.fromarray(a.astype(np.uint8)).filter(ImageFilter.UnsharpMask(1.5, 60, 2)))
    return atkinson(a)


def blue_noise(n=64, sig=1.9, seed=7):
    """Void-and-cluster ranks, scaled to 0..255."""
    rng = np.random.default_rng(seed)
    f = np.fft.fftfreq(n)
    k = np.exp(-2 * np.pi ** 2 * sig ** 2 * (f[:, None] ** 2 + f[None, :] ** 2))
    blur = lambda m: np.real(np.fft.ifft2(np.fft.fft2(m) * k))
    pat = np.zeros((n, n), bool); pat.flat[rng.choice(n * n, n * n // 10, replace=False)] = True
    while True:
        c = np.argmax(np.where(pat, blur(pat), -1e9)); pat.flat[c] = False
        v = np.argmin(np.where(pat, 1e9, blur(pat)))
        if v == c:
            pat.flat[c] = True; break
        pat.flat[v] = True
    rank = np.zeros(n * n, int); ones = int(pat.sum())
    p = pat.copy()
    for r in range(ones - 1, -1, -1):
        c = np.argmax(np.where(p, blur(p), -1e9)); p.flat[c] = False; rank[c] = r
    p = pat.copy()
    for r in range(ones, n * n):
        v = np.argmin(np.where(p, 1e9, blur(p))); p.flat[v] = True; rank[v] = r
    return (rank.reshape(n, n) * 256 // (n * n)).astype(np.uint8)


def c_array(name, data, per_line=25):
    lines = [', '.join(f'0x{b:02x}' for b in data[i:i + per_line]) for i in range(0, len(data), per_line)]
    return f'static const uint8_t {name}[{len(data)}] PROGMEM = {{\n  ' + ',\n  '.join(lines) + '\n};\n'


def main():
    bits = scene(sys.argv[1])
    packed = np.packbits(bits, axis=1).flatten()
    bn = blue_noise().flatten()
    out = os.path.join(os.path.dirname(__file__), '..', 'src', 'EinkScene.h')
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/make_eink_scene.py. Do not edit by hand.\n#pragma once\n#include <Arduino.h>\n\n')
        f.write(c_array('EINK_SCENE', packed))
        f.write('\n' + c_array('EINK_BLUE', bn, 32))
    print('wrote', os.path.normpath(out))


if __name__ == '__main__':
    main()
